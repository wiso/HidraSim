#!/usr/bin/env python3
"""Write a Geant4 macro for the sampling-fraction study.

Point-like beam along +z, aimed at the centre of the calorimeter front face.
The calorimeter is placed with /tbgeo/xshift = /tbgeo/yshift = 0, so its
geometric centre (centre of the module grid, which is symmetric for the TB25
layout) sits on the z axis at z = 0.  With non-zero tilts the front face
centre moves off-axis; the beam (x0, y0) is computed so that the beam line
goes through it.

Rotation convention (DREMTubesDetectorConstruction::DefineVolumes):
    R = rotY(-horizrot) * rotX(-vertrot), applied to the calorimeter.
Front-face centre in the calorimeter frame is (0, 0, -L/2), with
L = moduleZ + SiPM thickness = 2500 mm + 0.36 mm.

Usage:
    make_macro.py --energy 40 --nevents 50 --seed 17 [--horizrot 2.5 --vertrot 2.5]
                  [--particle e+] [--target face|centre] [--beam point|square --halfx 20 --halfy 20] > job.mac
"""
import argparse
import math

CALO_LENGTH_MM = 2500.0 + 0.36


def beam_xy(horizrot_deg, vertrot_deg, target):
    """Return (x0, y0) in mm of the beam line."""
    if target == "centre":  # 3D centre of the calorimeter box
        return 0.0, 0.0
    h = math.radians(-horizrot_deg)
    v = math.radians(-vertrot_deg)
    c = CALO_LENGTH_MM / 2.0
    # p = (0, 0, -c); rotX(v): y = sin(v) c, z = -cos(v) c; rotY(h): x = sin(h) z
    y = math.sin(v) * c
    z = -math.cos(v) * c
    x = math.sin(h) * z
    return x, y


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--energy", type=float, required=True, help="GeV")
    ap.add_argument("--nevents", type=int, required=True)
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--particle", default="e+")
    ap.add_argument("--horizrot", type=float, default=2.5, help="deg")
    ap.add_argument("--vertrot", type=float, default=2.5, help="deg")
    ap.add_argument("--target", choices=["face", "centre"], default="face")
    ap.add_argument("--beam", choices=["point", "square"], default="point",
                    help="point-like beam, or uniform rectangle (test-beam trigger 4x4 cm^2)")
    ap.add_argument("--halfx", type=float, default=20.0, help="mm, half side along x for --beam square")
    ap.add_argument("--halfy", type=float, default=20.0, help="mm, half side along y for --beam square")
    ap.add_argument("--dx", type=float, default=0.0, help="mm, shift of the beam centre along x (e.g. scan within the fibre cell)")
    ap.add_argument("--dy", type=float, default=0.0, help="mm, shift of the beam centre along y")
    ap.add_argument("--setcut", type=float, default=None, help="mm, global production cut (/run/setCut); default: physics-list default 0.7 mm")
    a = ap.parse_args()

    x0, y0 = beam_xy(a.horizrot, a.vertrot, a.target)
    x0, y0 = x0 + a.dx, y0 + a.dy
    if a.beam == "point":
        beam = f"/gps/pos/type Point\n/gps/position {x0:.3f} {y0:.3f} -3500 mm"
    else:  # uniform rectangle in the plane z = -3500 mm, centred on the same beam line
        beam = (f"/gps/pos/type Plane\n/gps/pos/shape Square\n/gps/pos/centre {x0:.3f} {y0:.3f} -3500 mm\n"
                f"/gps/pos/halfx {a.halfx:g} mm\n/gps/pos/halfy {a.halfy:g} mm")
    cut = f"/run/setCut {a.setcut:g} mm\n" if a.setcut is not None else ""
    print(f"""# Sampling-fraction study: generated by sampling/make_macro.py
# E = {a.energy} GeV, {a.particle}, {a.beam} beam on calorimeter {a.target}
/tbgeo/xshift 0 mm
/tbgeo/yshift 0 mm
/tbgeo/horizrot {a.horizrot} deg
/tbgeo/vertrot {a.vertrot} deg
{cut}/run/initialize
/run/printProgress 10
/gps/particle {a.particle}
/gps/energy {a.energy} GeV
/gps/direction 0 0 1
{beam}
/random/setSeeds {a.seed} {a.seed * 7 + 13}
/run/beamOn {a.nevents}""")


if __name__ == "__main__":
    main()
